-- Users, invitations and RBAC.

-- 1. Email uniqueness only among live users, so a deleted user's email can be reused.
ALTER TABLE users DROP CONSTRAINT uq_users_email;
CREATE UNIQUE INDEX uq_users_email_active ON users (email) WHERE is_deleted = FALSE;

-- Bumped when role or enabled/deleted state changes: access tokens issued before it and older web sessions are rejected.
ALTER TABLE users ADD COLUMN access_changed_at TIMESTAMPTZ NOT NULL DEFAULT now();

-- 2. Invitations (one-time link; only the SHA-256 of the token is stored).
CREATE TABLE invitations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_on       TIMESTAMPTZ  NOT NULL,
    updated_on       TIMESTAMPTZ  NOT NULL,
    is_active        BOOLEAN      NOT NULL DEFAULT TRUE,
    is_deleted       BOOLEAN      NOT NULL DEFAULT FALSE,
    email            VARCHAR(254) NOT NULL,
    role             VARCHAR(20)  NOT NULL,
    invited_by       BIGINT       NOT NULL REFERENCES users (id),
    token_hash       VARCHAR(64)  NOT NULL,
    expires_at       TIMESTAMPTZ  NOT NULL,
    accepted_at      TIMESTAMPTZ,
    revoked_at       TIMESTAMPTZ,
    accepted_user_id BIGINT REFERENCES users (id),
    CONSTRAINT uq_invitations_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_invitations_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT ck_invitations_role CHECK (role IN ('ADMIN', 'MANAGER', 'MEMBER'))
);

-- At most one pending (not accepted, not revoked) invitation per email.
CREATE UNIQUE INDEX uq_invitations_pending_email ON invitations (email)
    WHERE accepted_at IS NULL AND revoked_at IS NULL;
CREATE INDEX idx_invitations_invited_by ON invitations (invited_by);

-- 3. Audit: target of the action, plus value checks that mirror the Java enums.
-- Adding a UserAction value needs a new migration that replaces ck_user_log_action.
ALTER TABLE user_log ADD COLUMN target_type VARCHAR(20);
ALTER TABLE user_log ADD COLUMN target_id BIGINT;
ALTER TABLE user_log ADD CONSTRAINT ck_user_log_target_type CHECK (target_type IN ('USER', 'INVITATION'));
ALTER TABLE user_log ADD CONSTRAINT ck_user_log_target_pair
    CHECK ((target_type IS NULL AND target_id IS NULL) OR (target_type IS NOT NULL AND target_id IS NOT NULL));
ALTER TABLE user_log ADD CONSTRAINT ck_user_log_action CHECK (action IN (
    'LOGIN', 'LOGOUT', 'PASSWORD_CHANGED', 'REFRESH_REUSE_DETECTED', 'SETUP_COMPLETED',
    'USER_UPDATED', 'USER_ROLE_CHANGED', 'USER_DISABLED', 'USER_ENABLED', 'USER_DELETED',
    'INVITATION_CREATED', 'INVITATION_REVOKED', 'INVITATION_ACCEPTED'));
ALTER TABLE user_log ADD CONSTRAINT ck_user_log_sub_action CHECK (sub_action IN ('SUCCESS', 'FAILURE'));

CREATE INDEX idx_user_log_created_on ON user_log (created_on);
CREATE INDEX idx_user_log_target ON user_log (target_type, target_id);
