-- Teams and team membership (groups of people inside the one organization; not tenants).

CREATE TABLE teams (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_on  TIMESTAMPTZ  NOT NULL,
    updated_on  TIMESTAMPTZ  NOT NULL,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    CONSTRAINT ck_teams_name_not_blank CHECK (length(btrim(name)) > 0)
);

-- Names are unique case-insensitively among live teams; a deleted team's name can be reused.
CREATE UNIQUE INDEX uq_teams_name_active ON teams (lower(name)) WHERE is_deleted = FALSE;

CREATE TABLE team_members (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_on TIMESTAMPTZ NOT NULL,
    updated_on TIMESTAMPTZ NOT NULL,
    is_active  BOOLEAN     NOT NULL DEFAULT TRUE,
    is_deleted BOOLEAN     NOT NULL DEFAULT FALSE,
    team_id    BIGINT      NOT NULL REFERENCES teams (id),
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    team_role  VARCHAR(20) NOT NULL,
    CONSTRAINT uq_team_members_team_user UNIQUE (team_id, user_id),
    CONSTRAINT ck_team_members_team_role CHECK (team_role IN ('LEAD', 'MEMBER'))
);

-- Membership lookup by user (every request loads the caller's memberships).
CREATE INDEX idx_team_members_user_id ON team_members (user_id);

